def main():
    # 既存読み込み（BOM付きUTF-8）
    with open(CSV, "r", encoding="utf-8-sig", newline="") as f:
        reader = list(csv.reader(f))
    header = reader[0]
    existing_ids = {r[0] for r in reader[1:] if r}

    # 列順チェック
    if header != HEADER:
        print("⚠ ヘッダーが想定と違います。中止します。")
        print("  実際:", header)
        print("  想定:", HEADER)
        return

    # バックアップ
    bak = CSV + "." + datetime.now().strftime("%Y%m%d_%H%M%S") + ".bak"
    shutil.copy2(CSV, bak)
    print("バックアップ作成:", bak)

    # 追記行を組み立て（重複idはスキップ）
    add, skip = [], []
    for iid,date,sev,cat,fname in ROWS:
        if iid in existing_ids:
            skip.append(iid); continue
        # 列: id,date,orientation,pages,severity,category,suit,industry,kouji_shubetsu,type_guess,type_conf,type_actual,nexco_no,filename
        row = [iid, date, "横", "", sev, cat, "", "", "", "", "", "", "", fname]
        add.append(row)

    # 書き戻し（既存そのまま＋追記）
    with open(CSV, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        for r in reader[1:]:
            if r: writer.writerow(r)
        for r in add:
            writer.writerow(r)

    print(f"\n✅ 追記: {len(add)} 件")
    for r in add: print("   ", r[0], r[13][:40])
    if skip:
        print(f"\n⏭ 既存idのためスキップ: {len(skip)} 件 → {skip}")
    print("\n完了。次は import-csv → upload-pdfs。")
    print("※ type/kouji_shubetsu等は空欄。後日、副社長に管理画面から入力してもらう。")

if __name__ == "__main__":
    main()
